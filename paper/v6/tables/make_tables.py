#!/usr/bin/env python3
"""Regenerate four specified tables from the supplied archived records.

Usage: python tables/make_tables.py DATA_DIR TABLES_DIR
Reads catalogue_metadata.json, lawson_generic.json, c4_startup_order.json and
phase6_work_precision_selected_fields.json from DATA_DIR and writes
tableS01_catalogue.tex, tableS02_lawson.tex, tableS05_adaptive_records.tex and
table06_startup.tex into TABLES_DIR.
"""
import json
import sys
from pathlib import Path

DATA, OUT = Path(sys.argv[1]), Path(sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)
DASH = r"\textemdash"


def esc(s):
    return s.replace("_", r"\_").replace("&", r"\&").replace("/", "/\\allowbreak ")


def val(x):
    return DASH if x is None else str(x)


# Table S1: catalogue coverage
cat = json.load(open(DATA / "catalogue_metadata.json"))["entries"]
prov = {"published": "P", "derived-from-published-construction": "D", "EXPINT-documentation": "E",
        "EXPINT-documentation/source-description": "E"}
xc = {"agrees": "A", "corrected file": "C", "regenerated": "R"}
lines = [f"{e['name']} & {esc(e['family'])} & {val(e['classical_order'])} & {val(e['stiff_order'])} & {val(e['weak_stiff_order'])} & "
         f"{e['stages']} & {'H' if e['history'] == 'nonlinear_history' else 'S'} & {val(e['stage_order'])} & {val(e['quadrature_order'])} & "
         f"{prov[e['provenance_status']]} & {xc[e['crosscheck']]}\\\\" for e in cat]
texS1 = r"""\begingroup\footnotesize\renewcommand{\arraystretch}{0.92}
\begin{longtable}{@{}lp{3.6cm}rrrrcrrcc@{}}
\caption{Metadata and recorded comparison classification of the 47 catalogue entries. $p$: classical order; $p_s$: recorded stiff order; $p_w$: explicitly recorded weak or conditional stiff order; $s$: stages; L: external layout, S solution only or H with nonlinear history; $Q,P$: stage and quadrature orders where the construction uses them. Prov.: provenance of the canonical coefficients, P published formula transcribed, D derived from the published construction in exact arithmetic, E taken from the EXPINT documentation. X: classification recorded in the supplied metadata, A agreement, C agreement after a one-line correction, R regenerated coefficients. The supplied summary supports the aggregate count of 42 A entries and names the C/R exceptions; it does not enumerate all 42 comparisons. This table is not a generator-to-test coverage map. A dash is an undeclared field. Generated by \texttt{tables/make\_tables.py} from \texttt{catalogue\_metadata.json}.}\label{tab:catalogue47}\\
\toprule Entry & Family & $p$ & $p_s$ & $p_w$ & $s$ & L & $Q$ & $P$ & Prov. & X\\\midrule\endfirsthead
\multicolumn{11}{l}{\textit{Table \thetable\ continued}}\\\toprule Entry & Family & $p$ & $p_s$ & $p_w$ & $s$ & L & $Q$ & $P$ & Prov. & X\\\midrule\endhead
\bottomrule\endfoot
""" + "\n".join(lines) + "\n\\end{longtable}\\endgroup\n"
(OUT / "tableS01_catalogue.tex").write_text(texS1)

# Table S2: generalized Lawson convergence
law = json.load(open(DATA / "lawson_generic.json"))
lines = [f"{r['seed']} & {r['method']} & {r['classical_order']} & " + " & ".join(f"{s:.2f}" for s in r["slopes"]) + f" & {r['errors'][-1]:.2e}\\\\"
         for r in law["rows"]]
texS2 = r"""\begin{table}[p]
\centering\small
\caption{Generic classical convergence of the generalized Lawson families and three controls. Six-dimensional system $y'=Ay+0.3\sin y+f(t)$ with a random symmetric negative definite $A$ (seeds 1729 and 2718), manufactured solution $y_i=a_i\cos(\omega_it+p_i)$, dense exact actions, exact history and window $[0.8,1.6]$; every method integrates the window with its own steps $h=0.2,0.1,0.05,0.025$. Slopes are adjacent observed orders; the last column is the error at $h=0.025$. Generated by \texttt{tables/make\_tables.py} from \texttt{lawson\_generic.json}, the output of \texttt{benchmarks/lawson\_generic.py}.}\label{tab:lawson}
\begin{tabular}{@{}llcccc c@{}}\toprule
Seed & Method & $p$ & $0.2\to0.1$ & $0.1\to0.05$ & $0.05\to0.025$ & Error\\\midrule
""" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
(OUT / "tableS02_lawson.tex").write_text(texS2)

# Startup study: expose absolute errors instead of a fragile quotient.
st = json.load(open(DATA / "c4_startup_order.json"))
rows = sorted([r for r in st["rows"] if r["classical_order"] >= 5 or r["method"] in ("ABNorsett4", "PEC423", "EGLM433")],
              key=lambda r: (r["classical_order"], r["method"]))
lines = [f"{r['method']} & {r['classical_order']} & {r['slopes_exact_history'][1]:.2f} & {r['slopes_default_startup'][1]:.2f} & {r['error_exact_history'][-1]:.2e} & {r['error_default_startup'][-1]:.2e}\\\\" for r in rows]
tex6 = r"""\begin{table}[t]
\centering\small
\caption{End-to-end convergence on the scalar problem, $0\le t\le1$, with exact history (E) and one HochOst4 step per numerical-startup interval (S). Slopes use the intermediate pair $h=0.05$ to $h=0.025$; the last two columns give both errors at $h=0.0125$. Some exact-history errors are close to machine precision, so their ratios are not interpreted as stable factors of degradation. Generated from the complete error arrays in \texttt{c4\_startup\_order.json}; the named simulation driver and its execution log belong to the separate software companion.}\label{tab:startup}
\begin{tabular}{@{}lrrrrr@{}}\toprule
Method & $p$ & Slope E & Slope S & Error E & Error S\\\midrule
""" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
(OUT / "table06_startup.tex").write_text(tex6)

# Table S5: step-doubling records of the development experiment
d = json.load(open(DATA / "phase6_work_precision_selected_fields.json"))["cases"]
d.sort(key=lambda c: (c["problem"], c["method"], c["backend"], c["rtol"]))
lines = [f"{c['problem']} & {c['method']} & {c['backend']} & {c['rtol']:.0e} & {c['error_inf']:.2e} & {c['matvecs']} & {c['nonlinear_evals']} & {c['accepted']}/{c['rejected']}\\\\" for c in d]
texS5 = r"""\begin{table}[p]
\centering\small
\caption{Records of an earlier development experiment with the generic step-doubling controller (three complete method steps per trial, hence $3s$ nonlinear evaluations per attempt) on 128-dimensional periodic and Dirichlet problems with Krogstad and HochOst4, requested tolerances $10^{-4}$ and $10^{-7}$ (absolute tolerance $10^{-3}$ times rtol), and the KIOPS-type, real-Leja and calibrated selector realizations. Each row is one solve; no curve is fitted through the two tolerances. These are not ETD34 records. The calibrated selector of these runs kept its thresholds but, in the version used then, lost its calibration record when cloned by the solver, a defect corrected in the submitted version. Generated by \texttt{tables/make\_tables.py}.}\label{tab:phase6}
\begin{tabular}{@{}llllrrrc@{}}\toprule
Problem & Method & Backend & rtol & Error & Matvecs & $N$ evals & Acc./rej.\\\midrule
""" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
(OUT / "tableS05_adaptive_records.tex").write_text(texS5)
print("tables written:", len(cat), "catalogue rows;", len(law["rows"]), "Lawson rows;", len(rows), "startup rows;", len(d), "adaptive rows")
